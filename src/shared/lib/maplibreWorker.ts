import { setWorkerUrl } from 'maplibre-gl';
import workerUrl from 'maplibre-gl/dist/maplibre-gl-worker.mjs?worker&url';

/**
 * Адрес фонового потока MapLibre.
 *
 * Библиотека держит воркер отдельным файлом и ищет его рядом с собой:
 * `new URL('./maplibre-gl-worker.mjs', import.meta.url)`. После сборки Vite
 * модуль лежит в другом месте, файла по этому адресу нет — воркер молча не
 * поднимается. Растровая подложка при этом рисуется (она идёт мимо воркера), а
 * всё, что считается в нём, — линии и точки слоёв GeoJSON — не появляется
 * вовсе, и карта выглядит просто пустой.
 *
 * Здесь адрес берётся у сборщика. Именно `?worker&url`, а не `?url`: сам файл
 * воркера подтягивает соседний `maplibre-gl-shared.mjs`, и простой ресурс без
 * него в сборке остаётся нерабочим — в разработке сосед лежит рядом и всё
 * выглядит исправным, а в собранном виде воркер снова не поднимается.
 */
setWorkerUrl(workerUrl);

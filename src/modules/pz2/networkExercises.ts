/**
 * Упражнение «критический путь» (ТЗ ПЗ2 §7.2).
 *
 * Студенту показывают готовую сетевую диаграмму картинкой, он вводит
 * критический путь и сверяется с эталоном. Диаграммы и правильные ответы даёт
 * заказчик: «таких диаграмм я вам 3-4 сделал, они есть в настоящей ВСМ».
 *
 * СПИСОК ПУСТ НАМЕРЕННО. Ни картинок, ни эталонов нам ещё не передали — это
 * открытый вопрос в-8. Придумывать диаграмму и «правильный» путь нельзя:
 * упражнение проверяет ответ студента, и выдуманный эталон учил бы неверному.
 * Как только материалы придут, достаточно дописать сюда записи и положить
 * картинки в src/assets — экран заработает без правок кода.
 */
export interface Pz2NetworkExercise {
  id: string;
  title: string;
  /** Адрес картинки с сетевой диаграммой. */
  imageUrl: string;
  /** Что именно спрашивают у студента — формулировка заказчика. */
  question: string;
  /**
   * Эталонный ответ: последовательность событий критического пути.
   * Формат ответа тоже не подтверждён (в-8): здесь принято, что путь
   * записывается номерами событий по порядку.
   */
  answer: string[];
}

